def build(rows_by_cat, title, source, desc):
    cats = []
    for cid, zh in CAT_ZH.items():
        rows = rows_by_cat.get(cid, [])
        if not rows:
            continue
        companies = []
        for (sym, name, exch) in rows:
            companies.append({
                "ticker": sym,
                "name": name,
                "sector": zh,
                "exchange": exch,
                "intro": f"{exch}上市公司，主营业务：【{zh}】。",
                "website": f"https://finance.yahoo.com/quote/{sym}",
                "featured": False,
            })
        cats.append({"id": cid, "name": zh, "companies": companies})
    total = sum(len(c["companies"]) for c in cats)
    meta = {
        "title": title,
        "description": desc,
        "updated": "2026-10-27",
        "source": source,
        "total": total,
        "generatedBy": "人工整理代表性上市公司，按真实主营业务映射到共享分类体系；链接指向 Yahoo Finance 行情页。全量列表抓取脚本可在不受限网络补全。",
    }
    return {"meta": meta, "categories": cats}, total

